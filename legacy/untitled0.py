# Open the video file
cap = cv2.VideoCapture(video_file)
if not cap.isOpened():
    print(f"Error: Cannot open video file '{video_file}'.")
    raise Exception("Video file error")

# Get video properties
fps = cap.get(cv2.CAP_PROP_FPS)
frame_width = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
frame_height = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
total_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))

print(f"Video Properties:")
print(f"  FPS: {fps}")
print(f"  Resolution: {frame_width}x{frame_height}")
print(f"  Total Frames: {total_frames}")
print(f"  Duration: {total_frames/fps:.2f} seconds")

# Output video path
output_file = 'output_speed_tracking.mp4'

# Define codec and create VideoWriter
fourcc = cv2.VideoWriter_fourcc(*'mp4v')
out = cv2.VideoWriter(output_file, fourcc, fps, (512, int(512 * frame_height / frame_width)))

# Parameters for corner detection
feature_params = dict(
    maxCorners=200,
    qualityLevel=0.2,
    minDistance=5,
    blockSize=5
)

# Parameters for Lucas-Kanade optical flow
lk_params = dict(
    winSize=(15, 15),
    maxLevel=2,
    criteria=(cv2.TERM_CRITERIA_EPS | cv2.TERM_CRITERIA_COUNT, 10, 0.03)
)

# Read the first frame
ret, old_frame = cap.read()
if not ret:
    print("Cannot read video. Exiting...")
    cap.release()
    raise Exception("Cannot read video")

# Resize the first frame
old_frame = ResizeWithAspectRatio(old_frame, width=512)
old_gray = cv2.cvtColor(old_frame, cv2.COLOR_BGR2GRAY)

# Initialize saliency variables
prev_saliency = np.zeros_like(old_gray)
accumulated_saliency = np.zeros_like(old_gray, dtype=np.float32)

# Initialize key points
p0 = cv2.goodFeaturesToTrack(old_gray, mask=None, **feature_params)

# Initialize frame counter
frame_count = 0
recalc_interval = 30  # Recalculate key points every 30 frames

# Speed calculation parameters
scaling_factor = 0.1  # Adjust based on real-world calibration (meters per pixel)
frame_time = 1 / fps  # Time between frames in seconds

# Tracking dictionaries
vehicle_speeds = {}
speed_history = {}
vehicle_positions = {}

print("\n🚀 Processing video...")
print("=" * 60)

# Process video
while True:
    ret, frame = cap.read()
    if not ret:
        print("\n✓ Video processing complete!")
        break

    # Resize frame
    frame = ResizeWithAspectRatio(frame, width=512)
    frame_gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)

    # Generate motion saliency map
    motion_saliency = cv2.absdiff(old_gray, frame_gray)
    _, motion_saliency = cv2.threshold(motion_saliency, 30, 255, cv2.THRESH_BINARY)

    # Accumulate saliency map
    accumulated_saliency = cv2.addWeighted(
        accumulated_saliency, 0.9,
        motion_saliency.astype(np.float32), 0.1, 0
    )

    # Recalculate key points based on interval or saliency changes
    saliency_diff = cv2.absdiff(prev_saliency, motion_saliency)
    saliency_change = np.sum(saliency_diff) / (np.sum(motion_saliency) + 1e-6)

    if (frame_count % recalc_interval == 0 or p0 is None or
        len(p0) == 0 or saliency_change > 0.1):
        p0 = cv2.goodFeaturesToTrack(frame_gray, mask=motion_saliency, **feature_params)

    # Calculate optical flow
    if p0 is not None:
        p1, st, err = cv2.calcOpticalFlowPyrLK(old_gray, frame_gray, p0, None, **lk_params)

        # Select good points
        good_new = p1[st == 1]
        good_old = p0[st == 1]

        # Track vehicles
        new_vehicle_positions = {}
        new_speed_history = {}

        for i, (new, old) in enumerate(zip(good_new, good_old)):
            a, b = new.ravel()
            c, d = old.ravel()

            # Calculate displacement and speed
            displacement = np.sqrt((a - c) ** 2 + (b - d) ** 2)
            real_distance = displacement * scaling_factor
            speed_mps = real_distance / frame_time
            speed_kmh = speed_mps * 3.6

            if speed_kmh > 5:  # Only track if speed > 5 km/h
                assigned = False

                # Associate with existing vehicle
                for vehicle_id, centroid in vehicle_positions.items():
                    centroid_x, centroid_y = centroid
                    h, w = motion_saliency.shape
                    b_idx = max(0, min(h - 1, int(b)))
                    a_idx = max(0, min(w - 1, int(a)))

                    distance_threshold = 20 / (1 + motion_saliency[b_idx, a_idx] / 255.0)

                    if np.sqrt((a - centroid_x) ** 2 + (b - centroid_y) ** 2) < distance_threshold:
                        new_vehicle_positions[vehicle_id] = (
                            (vehicle_positions[vehicle_id][0] + a) / 2,
                            (vehicle_positions[vehicle_id][1] + b) / 2
                        )
                        new_speed_history.setdefault(
                            vehicle_id, speed_history.get(vehicle_id, [])
                        ).append(speed_kmh)

                        if len(new_speed_history[vehicle_id]) > 30:
                            new_speed_history[vehicle_id].pop(0)

                        assigned = True
                        break

                # Create new vehicle if not assigned
                if not assigned:
                    new_id = len(new_vehicle_positions)
                    new_vehicle_positions[new_id] = (a, b)
                    new_speed_history[new_id] = [speed_kmh]

        # Update tracking data
        vehicle_positions = new_vehicle_positions
        speed_history = new_speed_history

        # Draw speed annotations
        for vehicle_id, centroid in vehicle_positions.items():
            x, y = centroid
            average_speed_kmh = np.mean(speed_history[vehicle_id])

            cv2.putText(
                frame,
                f"{average_speed_kmh:.1f} km/h",
                (int(x), int(y) - 10),
                cv2.FONT_HERSHEY_SIMPLEX,
                0.5,
                (255, 255, 255),
                1,
                cv2.LINE_AA
            )

    # Create output with saliency overlay
    saliency_overlay = cv2.addWeighted(
        frame, 0.7,
        cv2.cvtColor(motion_saliency, cv2.COLOR_GRAY2BGR), 0.3, 0
    )

    # Write frame to output video
    out.write(saliency_overlay)

    # Progress indicator
    if frame_count % 30 == 0:
        progress = (frame_count / total_frames) * 100
        print(f"Progress: {progress:.1f}% ({frame_count}/{total_frames} frames)", end='\r')

    frame_count += 1
    old_gray = frame_gray.copy()
    prev_saliency = motion_saliency.copy()

# Release resources
cap.release()
out.release()

print("\n" + "=" * 60)
print(f"✓ Output saved as: {output_file}")
print(f"✓ Processed {frame_count} frames")

# Download the output video
files.download(output_file)
